    /// The findings of one run, in files of lines that repeat, of lines that do not, with
    /// a line past the end of its file and a file that cannot be read.
    fn findings_in(files: usize, lines: usize) -> Vec<Violation> {
        let mut found = Vec::new();
        for file in 0..files {
            for line in 1..=lines + 1 {
                found.push(Violation {
                    file: Some(format!("src/f{file}.rs")),
                    line: Some(line),
                    ..finding("t", "c/x")
                });
            }
        }
        found.push(Violation {
            file: Some("src/gone.rs".to_string()),
            line: Some(3),
            ..finding("t", "c/x")
        });
        found
    }

    /// The content of `src/f<n>.rs`: every third line is one text, the others differ by
    /// their number and by the file.
    fn content_of(path: &str, lines: usize) -> Option<String> {
        let file = path.strip_prefix("src/f")?.strip_suffix(".rs")?;
        Some(
            (0..lines)
                .map(|i| {
                    if i % 3 == 0 {
                        "    same();\n".to_string()
                    } else {
                        format!("  line {i} of {file}\n")
                    }
                })
                .collect(),
        )
    }

    /// The fingerprint a run gives each finding is the one the finding has read alone:
    /// the file read once for the run answers as the file read for the finding does.
    #[test]
    fn the_findings_of_a_run_have_the_fingerprints_they_have_alone() {
        let mut found = findings_in(3, 30);
        let reads = std::cell::Cell::new(0);
        fill_fingerprints(&mut found.iter_mut().collect::<Vec<_>>(), |path| {
            reads.set(reads.get() + 1);
            content_of(path, 30)
        });
        for v in &found {
            assert_eq!(
                v.fingerprint,
                compute_violation_fingerprint_with_content(v, |path| content_of(path, 30)),
                "{:?} line {:?}",
                v.file,
                v.line
            );
        }
        // The lines that repeat are told apart, so every finding has its own.
        let distinct: std::collections::HashSet<&String> =
            found.iter().map(|v| &v.fingerprint).collect();
        assert_eq!(distinct.len(), found.len());
    }

    /// The findings of one file cost steps in proportion to their number, and the file
    /// is read once. Before #672 the file was read for each finding, and its lines
    /// above the finding counted again for each.
    #[test]
    fn the_findings_of_one_file_cost_steps_in_proportion_to_their_number() {
        let steps_of = |lines: usize| -> (u64, usize) {
            let mut found = findings_in(1, lines);
            let reads = std::cell::Cell::new(0);
            let ((), counted) = crate::ast::ancestry::steps(|| {
                fill_fingerprints(&mut found.iter_mut().collect::<Vec<_>>(), |path| {
                    reads.set(reads.get() + 1);
                    content_of(path, lines)
                })
            });
            (counted, reads.get())
        };
        let ((few, read_few), (many, read_many)) = (steps_of(40), steps_of(160));
        assert!(
            few > 0 && many < 5 * few,
            "{few} steps for 40, {many} for 160"
        );
        // The file of the findings, and the one that cannot be read.
        assert_eq!((read_few, read_many), (2, 2));
    }

    /// The findings of one file left after a baseline of `entries` (version 2) is
    /// applied, by line; how many times a file was read; and the steps counted.
    fn left_after(lines: usize, entries: Vec<String>) -> (Vec<usize>, usize, u64) {
        let mut found = findings_in(1, lines);
        fill_fingerprints(&mut found.iter_mut().collect::<Vec<_>>(), |path| {
            content_of(path, lines)
        });
        let mut out = GateOutcome::new("unsafe-safety-comment");
        out.violations = found;
        let baseline = DisciplineBaseline {
            version: 2,
            findings: entries
                .into_iter()
                .map(|fingerprint| BaselineEntry {
                    gate: "unsafe-safety-comment".to_string(),
                    rule: "c/x".to_string(),
                    path: "src/f0.rs".to_string(),
                    fingerprint,
                })
                .collect(),
        };
        let mut outcomes = vec![out];
        let reads = std::cell::Cell::new(0);
        let ((), counted) = crate::ast::ancestry::steps(|| {
            apply_baseline_with_reader(
                |path| {
                    reads.set(reads.get() + 1);
                    content_of(path, lines)
                },
                &baseline,
                &mut outcomes,
            );
        });
        (
            outcomes[0]
                .violations
                .iter()
                .filter_map(|v| v.line)
                .collect(),
            reads.get(),
            counted,
        )
    }

    /// A finding a baseline does not hold under its own fingerprint is looked for under
    /// the one its line has on its first occurrence, and the file is read once for all
    /// of them. Before #672 it was read for each finding, and its lines above the
    /// finding counted again for each.
    #[test]
    fn findings_a_baseline_does_not_hold_are_looked_up_with_their_file_read_once() {
        // `same();` stands on every third line, from the first. A baseline written
        // before occurrences were told apart holds the first one's fingerprint once
        // for each of the first three.
        let first = compute_violation_fingerprint_with_content(
            &Violation {
                file: Some("src/f0.rs".to_string()),
                line: Some(1),
                ..finding("t", "c/x")
            },
            |path| content_of(path, 30),
        );
        let (left, reads, _) = left_after(30, vec![first.clone(), first.clone(), first.clone()]);
        // Lines 1, 4 and 7 are accepted, the later occurrences and every other line
        // are not; the line past the end and the file that cannot be read stay.
        let wanted: Vec<usize> = (1..=31)
            .filter(|l| ![1, 4, 7].contains(l))
            .chain([3])
            .collect();
        assert_eq!(left, wanted);
        // The file of the findings, and the one that cannot be read.
        assert_eq!(reads, 2);
        let ((_, read_few, few), (_, read_many, many)) = (
            left_after(40, vec![first.clone()]),
            left_after(160, vec![first]),
        );
        assert_eq!((read_few, read_many), (2, 2));
        assert!(
            few > 0 && many < 5 * few,
            "{few} steps for 40, {many} for 160"
        );
    }

