    #[test]
    fn a_line_less_finding_is_keyed_by_its_anchor_never_its_message() {
        let none = |_: &str| None;
        let anchored = |anchor: &str, message: &str| Violation {
            anchor: Some(anchor.to_string()),
            message: message.to_string(),
            ..finding("t", "deletion-rationale/test-removed-without-rationale")
        };
        let one = anchored("test_one", "Test `test_one` was removed.");
        // A reworded message keeps the fingerprint; another anchor changes it.
        assert_eq!(
            fingerprint_for_version(&one, none, 2),
            fingerprint_for_version(&anchored("test_one", "`test_one` is gone."), none, 2)
        );
        assert_ne!(
            fingerprint_for_version(&one, none, 2),
            fingerprint_for_version(
                &anchored("test_two", "Test `test_one` was removed."),
                none,
                2
            )
        );
        // No anchor: version 2 hashes nothing past the path, version 1 the message.
        let plain = finding("t", "c/x");
        let reworded = Violation {
            message: "reworded".into(),
            ..finding("t", "c/x")
        };
        assert_eq!(
            fingerprint_for_version(&plain, none, 2),
            fingerprint_for_version(&reworded, none, 2)
        );
        assert_ne!(
            fingerprint_for_version(&plain, none, 1),
            fingerprint_for_version(&reworded, none, 1)
        );
        // Identical source lines stay apart by their anchors.
        let read = |_: &str| Some("@Test\n@Test\n".to_string());
        let at = |line, anchor: &str| Violation {
            line: Some(line),
            ..anchored(anchor, "m")
        };
        assert_ne!(
            fingerprint_for_version(&at(1, "a"), read, 2),
            fingerprint_for_version(&at(2, "b"), read, 2)
        );
        assert_eq!(
            fingerprint_for_version(&at(1, "a"), read, 1),
            fingerprint_for_version(&at(2, "b"), read, 1),
            "version 1 is unchanged"
        );
    }

    /// Anchoring a kind changes its version-2 fingerprint and nothing about version 1: a
    /// version-1 baseline keeps matching, with or without a readable line.
    #[test]
    fn an_anchor_never_changes_a_version_one_fingerprint() {
        let none = |_: &str| None;
        let read = |_: &str| Some("  let x = danger();  \n".to_string());
        for line in [None, Some(1)] {
            let plain = Violation {
                line,
                ..finding("Old Title", "gate/code")
            };
            let anchored = Violation {
                anchor: Some("job:lint".to_string()),
                ..plain.clone()
            };
            assert_eq!(
                fingerprint_for_version(&plain, read, 1),
                fingerprint_for_version(&anchored, read, 1),
                "line {line:?}"
            );
            assert_eq!(
                fingerprint_for_version(&plain, none, 1),
                fingerprint_for_version(&anchored, none, 1),
                "line {line:?}, unreadable"
            );
            assert_ne!(
                fingerprint_for_version(&plain, read, 2),
                fingerprint_for_version(&anchored, read, 2),
                "line {line:?}: version 2 does hash the anchor"
            );
        }
        // The version-1 formula itself: gate, title, path and the hash of the message
        // (no line) or of the trimmed source line.
        let anchored = Violation {
            anchor: Some("job:lint".to_string()),
            ..finding("Old Title", "gate/code")
        };
        let v1 = |content: &str| {
            sha256_hex(
                format!(
                    "unsafe-safety-comment:Old Title:src/lib.rs:{}",
                    sha256_hex(content.as_bytes())
                )
                .as_bytes(),
            )
        };
        assert_eq!(
            fingerprint_for_version(&anchored, none, 1),
            v1("unsafe block")
        );
        let at_line = Violation {
            line: Some(1),
            ..anchored
        };
        assert_eq!(
            fingerprint_for_version(&at_line, read, 1),
            v1("let x = danger();")
        );
    }

